// Package eval 是 OryxOS 的評測 harness：吃一份 YAML 用例宣告，在乾淨的 Workspace 裡
// 佈置初始檔案、把任務送給**真實 Agent** 跑一輪，用宣告式斷言判卷。
//
// **它會呼叫真實 Provider 並產生費用，因此不是 `go test` 的一部分。** 憲法 4.4 明訂
// 自動化測試中 LLM 一律回放錄製回應、絕不打真實 API；而評測的價值恰恰在於用真實模型
// ——錄製回放測得出「程式碼行為正確」，測不出「Agent 行為有沒有退步」。兩者是不同的
// 保證，所以由不同的東西承擔。
//
// 本 package 分成兩層，切法是本設計的核心：
//
//   - **判卷（case.go、grade.go）是純函式**：吃「用例宣告 ＋ 一次執行的結果摘要」，
//     吐「通過與否 ＋ 未通過原因」，完全不碰 Provider。這是主要的測試面，表格驅動。
//   - **驅動（run.go）不寫自動化測試**：它呼叫真實 Provider，正確性由執行時的實際
//     使用承擔（需求文檔第 13 章）。切乾淨之後這一層只剩沒有分支的組裝與傳遞。
//
// 佈置（workspace.go）與結果紀錄（record.go）都落在判卷那一側：前者只碰檔案系統，而
// 「每個用例前建立乾淨的 Workspace」正是評測結果可信的前提；後者把一次執行收斂成一行
// 結構化結果並**追加**進歷史檔案，讓「這次比上次多用了兩個 iteration」說得出口
// （ticket #53）。兩者都測得到，所以都放在這一側。
