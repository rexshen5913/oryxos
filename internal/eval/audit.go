package eval

import "fmt"

// CheckAuditComplete 在指標被採信之前，確認這一輪的審計記錄一筆都沒有漏；lost 是
// 沒落庫的筆數（見 storage.AuditLog.LostWrites）。
//
// **為什麼這道檢查非有不可**（ticket #53 外部審查第一輪抓到）：
//
// 審計是旁路——佇列滿就丟棄、寫入失敗就記日誌，兩者都絕不中斷使用者的對話。那條
// 規則沒有問題，也不該為了評測而改。問題在於本票新增的兩種斷言都是**上限**：
//
//	max_iterations: 3      實際 iteration 數 ≤ 3 才通過
//	max_tool_failures: 0   實際 Tool 失敗數 ≤ 0 才通過
//
// 審計漏記一筆的方向，是讓實際值**變小**。而變小的實際值更容易通過上限——**漏記會
// 產生綠燈**。這與既有的 tool_called 方向正好相反：那條斷言在記錄漏列時判失敗，人會
// 去查；一條因為資料不全而變綠的斷言則不會有人去查，而評測宣稱了一個它根本沒驗證的
// 性質。整個評測設計裡最不能出現的就是這種假綠燈。
//
// 成本那一邊也一樣：MetricsForSession 用「呼叫總數 == 算得出成本的筆數」判斷總額能不能
// 採信，但它數的是**已經落庫的那些行**。一筆已定價的記錄若根本沒寫進去，兩個數字仍然
// 相等，於是回傳一個少算的部分和——正是那條規則要防的東西。
//
// 處置是把用例判成**執行錯誤**而不是「未通過」：審計漏記不代表 Agent 做錯了什麼，它
// 代表這一次的觀測不可信。兩者的處置不同——未通過要去改 Agent，執行錯誤要去查機器。
//
// 是純函式而不是寫在 RunCase 裡的一行 if：驅動層呼叫真實 Provider，沒有自動化測試
// （憲法 4.4），而這條規則的方向性正是最不能被日後重構悄悄拿掉的東西。與 Record.Summary
// 不寫在 cmd/oryxos-eval 是同一條理由——有判斷的東西要放在測得到的那一側。
func CheckAuditComplete(lost uint64) error {
	if lost == 0 {
		return nil
	}
	return fmt.Errorf("有 %d 筆審計記錄沒有落庫（佇列滿或寫入資料庫失敗，詳見 Workspace 的 logs/）；"+
		"iteration 數與 Tool 失敗數都由審計表算出，漏記會讓它們偏低而讓上限斷言假通過，"+
		"因此本輪不判卷", lost)
}
